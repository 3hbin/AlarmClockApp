 * Ngôn ngữ của app. Hỗ trợ: Tiếng Việt, English, हिन्दी, Русский, 中文, 한국어, 日本語, Français.
 * Ngôn ngữ khác (hoặc hệ thống không hỗ trợ) → dùng tiếng Anh.
 * Chữ chưa có bản dịch riêng → dùng tiếng Anh.
 */
object LangPack {
    val SUPPORTED = setOf("vi", "en", "hi", "ru", "zh", "ko", "ja", "fr")

    @Volatile private var cached: String = "vi"

    /** Mã ngôn ngữ đang dùng: vi / en / hi / ru / zh / ko / ja / fr. */
    fun resolve(context: Context): String {
        val pref = try { AppSettings.getLanguage(context) } catch (_: Exception) { LanguageCatalog.SYSTEM }
        val code = if (pref == LanguageCatalog.SYSTEM || pref.isBlank()) {
            val sys = Locale.getDefault().language.lowercase(Locale.ROOT)
            if (sys in SUPPORTED) sys else "en"
        } else {
            val base = pref.replace('_', '-').lowercase(Locale.ROOT).substringBefore('-')
            if (base in SUPPORTED) base else "en"
        }
        cached = code
        return code
    }

    fun current(): String = cached

    /** Chọn chữ theo ngôn ngữ; không có bản dịch thì dùng tiếng Anh. */
    fun text(code: String, vi: String, en: String): String {
        if (code == "vi") return vi
        if (code == "en") return en
        return dict[code]?.get(vi.trim()) ?: en
    }

    /** Bản dịch riêng (khóa là chữ tiếng Việt gốc). */
    fun lookup(code: String, vi: String): String? = dict[code]?.get(vi.trim())

